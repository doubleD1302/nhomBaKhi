-- Đề 25 / PostgreSQL 14+ / khởi tạo trên schema viec_lam còn trống.
-- Không DROP DATABASE, không xóa dữ liệu đang có. Chạy: schema -> functions -> views -> seed.
BEGIN;
CREATE SCHEMA IF NOT EXISTS viec_lam;
REVOKE ALL ON SCHEMA viec_lam FROM PUBLIC;
SET LOCAL search_path = viec_lam, public;

CREATE TABLE nguoi_dung (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(254) NOT NULL,
 mat_khau_hash varchar(100) NOT NULL CHECK (mat_khau_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
 ho_ten varchar(150) NOT NULL CHECK (btrim(ho_ten) <> ''),
 sdt varchar(20) NOT NULL CHECK (sdt ~ '^\+?[0-9]{9,15}$'),
 vai_tro varchar(25) NOT NULL CHECK (vai_tro IN ('SINH_VIEN','NHA_TUYEN_DUNG','QUAN_TRI')),
 trang_thai varchar(20) NOT NULL DEFAULT 'HOAT_DONG' CHECK (trang_thai IN ('HOAT_DONG','BI_KHOA')),
 ly_do_khoa text,
 tao_luc timestamptz NOT NULL DEFAULT now(),
 cap_nhat_luc timestamptz NOT NULL DEFAULT now(),
 CHECK (email = lower(btrim(email)) AND position('@' in email) > 1),
 CHECK (trang_thai <> 'BI_KHOA' OR nullif(btrim(ly_do_khoa),'') IS NOT NULL),
 UNIQUE(email)
);
CREATE TABLE ho_so_sinh_vien (
 id bigint PRIMARY KEY REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 truong varchar(200) NOT NULL CHECK (btrim(truong)<>''),
 nganh varchar(150) NOT NULL CHECK (btrim(nganh)<>''),
 nam_hoc smallint NOT NULL CHECK (nam_hoc BETWEEN 1 AND 8),
 ky_nang text NOT NULL DEFAULT '',
 gioi_thieu text NOT NULL DEFAULT '',
 avatar_url text,
 cap_nhat_luc timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE khung_gio_ranh (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sinh_vien_id bigint NOT NULL REFERENCES ho_so_sinh_vien(id) ON DELETE RESTRICT,
 thu_trong_tuan smallint NOT NULL CHECK (thu_trong_tuan BETWEEN 1 AND 7), -- ISO: 1=thứ Hai,7=CN
 gio_bat_dau time NOT NULL,
 gio_ket_thuc time NOT NULL,
 CHECK (gio_bat_dau < gio_ket_thuc),
 UNIQUE(sinh_vien_id,thu_trong_tuan,gio_bat_dau,gio_ket_thuc)
);
CREATE TABLE nha_tuyen_dung (
 id bigint PRIMARY KEY REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 ten_cong_ty varchar(200) NOT NULL CHECK (btrim(ten_cong_ty)<>''),
 ma_so_thue varchar(20) NOT NULL UNIQUE CHECK (btrim(ma_so_thue)<>''),
 dia_chi text NOT NULL CHECK (btrim(dia_chi)<>''),
 nguoi_lien_he varchar(150) NOT NULL CHECK (btrim(nguoi_lien_he)<>''),
 sdt_lien_he varchar(20) NOT NULL CHECK (sdt_lien_he ~ '^\+?[0-9]{9,15}$'),
 giay_phep_url text NOT NULL CHECK (btrim(giay_phep_url)<>''),
 trang_thai_duyet varchar(20) NOT NULL DEFAULT 'CHO_DUYET' CHECK (trang_thai_duyet IN ('CHO_DUYET','DA_DUYET','TU_CHOI')),
 da_xac_minh boolean GENERATED ALWAYS AS (trang_thai_duyet='DA_DUYET') STORED,
 ly_do_tu_choi text,
 duyet_boi bigint REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 duyet_luc timestamptz,
 CHECK (trang_thai_duyet='CHO_DUYET' OR (duyet_boi IS NOT NULL AND duyet_luc IS NOT NULL)),
 CHECK (trang_thai_duyet<>'TU_CHOI' OR nullif(btrim(ly_do_tu_choi),'') IS NOT NULL)
);
CREATE TABLE nhom_viec (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ten varchar(100) NOT NULL UNIQUE CHECK (btrim(ten)<>'')
);
CREATE TABLE khu_vuc (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ma varchar(30) NOT NULL UNIQUE CHECK (btrim(ma)<>''),
 ten varchar(150) NOT NULL CHECK (btrim(ten)<>'')
);
CREATE TABLE dia_diem_lam_viec (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ntd_id bigint NOT NULL REFERENCES nha_tuyen_dung(id) ON DELETE RESTRICT,
 khu_vuc_id bigint NOT NULL REFERENCES khu_vuc(id) ON DELETE RESTRICT,
 ten varchar(150) NOT NULL CHECK (btrim(ten)<>''),
 dia_chi text NOT NULL CHECK (btrim(dia_chi)<>''),
 vi_do numeric(10,7) NOT NULL CHECK (vi_do BETWEEN -90 AND 90),
 kinh_do numeric(10,7) NOT NULL CHECK (kinh_do BETWEEN -180 AND 180),
 ban_kinh_m integer NOT NULL DEFAULT 200 CHECK (ban_kinh_m BETWEEN 1 AND 5000),
 dang_hoat_dong boolean NOT NULL DEFAULT true,
 UNIQUE(id,ntd_id)
);
CREATE TABLE tin_tuyen_dung (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ntd_id bigint NOT NULL REFERENCES nha_tuyen_dung(id) ON DELETE RESTRICT,
 nhom_id bigint NOT NULL REFERENCES nhom_viec(id) ON DELETE RESTRICT,
 dia_diem_id bigint NOT NULL,
 tieu_de varchar(200) NOT NULL CHECK (btrim(tieu_de)<>''),
 mo_ta text NOT NULL CHECK (btrim(mo_ta)<>''),
 yeu_cau text NOT NULL DEFAULT '',
 luong_theo_gio numeric(12,2) NOT NULL CHECK (luong_theo_gio>0),
 so_luong integer NOT NULL CHECK (so_luong>0),
 han_ung_tuyen timestamptz NOT NULL,
 khong_thu_phi boolean NOT NULL DEFAULT false,
 khong_giu_giay_to boolean NOT NULL DEFAULT false,
 luong_ro_rang boolean NOT NULL DEFAULT false,
 trang_thai_duyet varchar(20) NOT NULL DEFAULT 'CHO_DUYET' CHECK (trang_thai_duyet IN ('CHO_DUYET','DA_DUYET','TU_CHOI','DA_GO','DA_DONG')),
 bi_gan_co boolean NOT NULL DEFAULT false,
 ly_do_gan_co text,
 ly_do_tu_choi text,
 ly_do_go text,
 duyet_boi bigint REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 duyet_luc timestamptz,
 tao_luc timestamptz NOT NULL DEFAULT now(),
 cap_nhat_luc timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(dia_diem_id,ntd_id) REFERENCES dia_diem_lam_viec(id,ntd_id) ON DELETE RESTRICT,
 CHECK (trang_thai_duyet<>'DA_DUYET' OR (khong_thu_phi AND khong_giu_giay_to AND luong_ro_rang)),
 CHECK (trang_thai_duyet='CHO_DUYET' OR (duyet_boi IS NOT NULL AND duyet_luc IS NOT NULL)),
 CHECK (trang_thai_duyet<>'TU_CHOI' OR nullif(btrim(ly_do_tu_choi),'') IS NOT NULL),
 CHECK (trang_thai_duyet<>'DA_GO' OR nullif(btrim(ly_do_go),'') IS NOT NULL),
 CHECK (NOT bi_gan_co OR nullif(btrim(ly_do_gan_co),'') IS NOT NULL)
);
CREATE TABLE lich_su_duyet_ntd (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ntd_id bigint NOT NULL REFERENCES nha_tuyen_dung(id) ON DELETE RESTRICT,
 trang_thai_cu varchar(20), trang_thai_moi varchar(20) NOT NULL,
 noi_dung text NOT NULL,
 nguoi_thuc_hien bigint NOT NULL REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 thuc_hien_luc timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE lich_su_duyet_tin (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tin_id bigint NOT NULL REFERENCES tin_tuyen_dung(id) ON DELETE RESTRICT,
 trang_thai_cu varchar(20), trang_thai_moi varchar(20) NOT NULL,
 noi_dung text NOT NULL,
 nguoi_thuc_hien bigint NOT NULL REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 thuc_hien_luc timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE ca_lam_viec (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tin_id bigint NOT NULL REFERENCES tin_tuyen_dung(id) ON DELETE RESTRICT,
 bat_dau timestamptz NOT NULL,
 ket_thuc timestamptz NOT NULL,
 so_nguoi_can integer NOT NULL CHECK (so_nguoi_can>0),
 trang_thai varchar(20) NOT NULL DEFAULT 'MO' CHECK (trang_thai IN ('MO','DA_DONG','DA_HUY')),
 -- Snapshot: thay đổi tin/địa điểm về sau không sửa lịch/đơn giá đã chốt.
 dia_chi_chot text NOT NULL,
 vi_do_chot numeric(10,7) NOT NULL CHECK (vi_do_chot BETWEEN -90 AND 90),
 kinh_do_chot numeric(10,7) NOT NULL CHECK (kinh_do_chot BETWEEN -180 AND 180),
 ban_kinh_m_chot integer NOT NULL CHECK (ban_kinh_m_chot BETWEEN 1 AND 5000),
 luong_theo_gio_chot numeric(12,2) NOT NULL CHECK (luong_theo_gio_chot>0),
 CHECK (ket_thuc>bat_dau AND ket_thuc<=bat_dau+interval '16 hours'),
 UNIQUE(id,tin_id)
);
CREATE TABLE ung_tuyen (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tin_id bigint NOT NULL REFERENCES tin_tuyen_dung(id) ON DELETE RESTRICT,
 sinh_vien_id bigint NOT NULL REFERENCES ho_so_sinh_vien(id) ON DELETE RESTRICT,
 loi_gioi_thieu text NOT NULL DEFAULT '',
 trang_thai varchar(20) NOT NULL DEFAULT 'CHO_XEM' CHECK (trang_thai IN ('CHO_XEM','CHAP_NHAN','TU_CHOI','DA_RUT')),
 ly_do text,
 ung_tuyen_luc timestamptz NOT NULL DEFAULT now(),
 xu_ly_luc timestamptz,
 xu_ly_boi bigint REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 UNIQUE(tin_id,sinh_vien_id)
);
CREATE TABLE nhan_ca (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ca_id bigint NOT NULL REFERENCES ca_lam_viec(id) ON DELETE RESTRICT,
 sinh_vien_id bigint NOT NULL REFERENCES ho_so_sinh_vien(id) ON DELETE RESTRICT,
 trang_thai varchar(20) NOT NULL DEFAULT 'DA_NHAN' CHECK (trang_thai IN ('DA_NHAN','DA_HUY')),
 don_gia_chot numeric(12,2) NOT NULL CHECK (don_gia_chot>0),
 nhan_luc timestamptz NOT NULL DEFAULT now(),
 huy_luc timestamptz,
 ly_do_huy text,
 UNIQUE(ca_id,sinh_vien_id),
 CHECK (trang_thai<>'DA_HUY' OR (huy_luc IS NOT NULL AND nullif(btrim(ly_do_huy),'') IS NOT NULL))
);
CREATE TABLE cham_cong (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nhan_ca_id bigint NOT NULL UNIQUE REFERENCES nhan_ca(id) ON DELETE RESTRICT,
 check_in_luc timestamptz NOT NULL,
 vi_do_in numeric(10,7) NOT NULL CHECK (vi_do_in BETWEEN -90 AND 90),
 kinh_do_in numeric(10,7) NOT NULL CHECK (kinh_do_in BETWEEN -180 AND 180),
 do_chinh_xac_in_m numeric(10,2) CHECK (do_chinh_xac_in_m>=0),
 check_out_luc timestamptz,
 vi_do_out numeric(10,7) CHECK (vi_do_out BETWEEN -90 AND 90),
 kinh_do_out numeric(10,7) CHECK (kinh_do_out BETWEEN -180 AND 180),
 do_chinh_xac_out_m numeric(10,2) CHECK (do_chinh_xac_out_m>=0),
 khoang_cach_in_m double precision NOT NULL,
 khoang_cach_out_m double precision,
 so_giay_hop_le integer NOT NULL DEFAULT 0 CHECK (so_giay_hop_le>=0),
 so_gio numeric(10,4) GENERATED ALWAYS AS (round(so_giay_hop_le/3600.0,4)) STORED,
 trang_thai_duyet varchar(20) NOT NULL DEFAULT 'CHO_DUYET' CHECK (trang_thai_duyet IN ('CHO_DUYET','CAN_DUYET_TAY','DA_DUYET','TU_CHOI')),
 duyet_boi bigint REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 duyet_luc timestamptz,
 ly_do_duyet text,
 CHECK (check_out_luc IS NULL OR check_out_luc>check_in_luc),
 CHECK ((check_out_luc IS NULL AND vi_do_out IS NULL AND kinh_do_out IS NULL)
     OR (check_out_luc IS NOT NULL AND vi_do_out IS NOT NULL AND kinh_do_out IS NOT NULL)),
 CHECK (trang_thai_duyet NOT IN ('DA_DUYET','TU_CHOI') OR (duyet_boi IS NOT NULL AND duyet_luc IS NOT NULL AND nullif(btrim(ly_do_duyet),'') IS NOT NULL)),
 CHECK (trang_thai_duyet<>'DA_DUYET' OR check_out_luc IS NOT NULL)
);
CREATE TABLE lich_su_duyet_cham_cong (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cham_cong_id bigint NOT NULL REFERENCES cham_cong(id) ON DELETE RESTRICT,
 trang_thai_cu varchar(20), trang_thai_moi varchar(20) NOT NULL,
 ly_do text NOT NULL,
 nguoi_thuc_hien bigint NOT NULL REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 thuc_hien_luc timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE ky_luong (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ntd_id bigint NOT NULL REFERENCES nha_tuyen_dung(id) ON DELETE RESTRICT,
 thang date NOT NULL CHECK (extract(day FROM thang)=1),
 trang_thai varchar(20) NOT NULL DEFAULT 'MO' CHECK (trang_thai IN ('MO','DA_KHOA')),
 UNIQUE(ntd_id,thang)
);
CREATE TABLE bang_luong (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ky_luong_id bigint NOT NULL REFERENCES ky_luong(id) ON DELETE RESTRICT,
 sinh_vien_id bigint NOT NULL REFERENCES ho_so_sinh_vien(id) ON DELETE RESTRICT,
 trang_thai varchar(20) NOT NULL DEFAULT 'NHAP' CHECK (trang_thai IN ('NHAP','DA_DUYET','DA_CHI_TRA')),
 tao_luc timestamptz NOT NULL DEFAULT now(),
 duyet_boi bigint REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 duyet_luc timestamptz,
 chi_tra_boi bigint REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 chi_tra_luc timestamptz,
 chung_tu_url text,
 CHECK (trang_thai='NHAP' OR (duyet_boi IS NOT NULL AND duyet_luc IS NOT NULL)),
 CHECK (trang_thai<>'DA_CHI_TRA' OR (chi_tra_boi IS NOT NULL AND chi_tra_luc IS NOT NULL AND nullif(btrim(chung_tu_url),'') IS NOT NULL)),
 UNIQUE(ky_luong_id,sinh_vien_id)
);
CREATE TABLE chi_tiet_luong (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bang_luong_id bigint NOT NULL REFERENCES bang_luong(id) ON DELETE RESTRICT,
 cham_cong_id bigint NOT NULL UNIQUE REFERENCES cham_cong(id) ON DELETE RESTRICT,
 so_giay_chot integer NOT NULL CHECK (so_giay_chot>0),
 don_gia_chot numeric(12,2) NOT NULL CHECK (don_gia_chot>0),
 thanh_tien numeric(16,0) GENERATED ALWAYS AS (round(so_giay_chot*don_gia_chot/3600,0)) STORED
);
CREATE TABLE lich_su_luong (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bang_luong_id bigint NOT NULL REFERENCES bang_luong(id) ON DELETE RESTRICT,
 hanh_dong varchar(20) NOT NULL CHECK (hanh_dong IN ('TAO_NHAP','TINH_LAI','DUYET','GHI_CHI_TRA')),
 nguoi_thuc_hien bigint NOT NULL REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 noi_dung text NOT NULL,
 thuc_hien_luc timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE bao_cao_lua_dao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tin_id bigint NOT NULL REFERENCES tin_tuyen_dung(id) ON DELETE RESTRICT,
 nguoi_bao_id bigint NOT NULL REFERENCES ho_so_sinh_vien(id) ON DELETE RESTRICT,
 noi_dung text NOT NULL CHECK (length(btrim(noi_dung))>=10),
 trang_thai varchar(20) NOT NULL DEFAULT 'MO' CHECK (trang_thai IN ('MO','DANG_XU_LY','DA_KET_LUAN','DA_HUY')),
 ket_luan text,
 xu_ly_boi bigint REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 tao_luc timestamptz NOT NULL DEFAULT now(),
 ket_luan_luc timestamptz,
 CHECK (trang_thai<>'DA_KET_LUAN' OR (xu_ly_boi IS NOT NULL AND ket_luan_luc IS NOT NULL AND nullif(btrim(ket_luan),'') IS NOT NULL))
);
CREATE TABLE bang_chung_bao_cao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bao_cao_id bigint NOT NULL REFERENCES bao_cao_lua_dao(id) ON DELETE RESTRICT,
 tep_url text NOT NULL CHECK (btrim(tep_url)<>''),
 mo_ta text NOT NULL DEFAULT '',
 tao_luc timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE lich_su_xu_ly_bao_cao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bao_cao_id bigint NOT NULL REFERENCES bao_cao_lua_dao(id) ON DELETE RESTRICT,
 trang_thai_cu varchar(20), trang_thai_moi varchar(20) NOT NULL,
 noi_dung text NOT NULL,
 nguoi_thuc_hien bigint NOT NULL REFERENCES nguoi_dung(id) ON DELETE RESTRICT,
 thuc_hien_luc timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_ranh_sv_thu ON khung_gio_ranh(sinh_vien_id,thu_trong_tuan);
CREATE INDEX idx_diem_khu ON dia_diem_lam_viec(khu_vuc_id);
CREATE INDEX idx_tin_tim_kiem ON tin_tuyen_dung(trang_thai_duyet,nhom_id,luong_theo_gio);
CREATE INDEX idx_tin_ntd ON tin_tuyen_dung(ntd_id);
CREATE INDEX idx_tin_dia_diem ON tin_tuyen_dung(dia_diem_id,ntd_id);
CREATE INDEX idx_ca_tin_gio ON ca_lam_viec(tin_id,bat_dau,ket_thuc);
CREATE INDEX idx_ung_tuyen_sv ON ung_tuyen(sinh_vien_id,trang_thai);
CREATE INDEX idx_nhan_ca_sv ON nhan_ca(sinh_vien_id,trang_thai);
CREATE INDEX idx_nhan_ca_ca ON nhan_ca(ca_id) WHERE trang_thai='DA_NHAN';
CREATE INDEX idx_cham_cong_duyet ON cham_cong(trang_thai_duyet);
CREATE INDEX idx_luong_sv ON bang_luong(sinh_vien_id,ky_luong_id);
CREATE INDEX idx_ct_luong_bang ON chi_tiet_luong(bang_luong_id);
CREATE INDEX idx_bao_cao_tin ON bao_cao_lua_dao(tin_id,trang_thai);
CREATE INDEX idx_bao_cao_sv ON bao_cao_lua_dao(nguoi_bao_id);
CREATE INDEX idx_bang_chung_bc ON bang_chung_bao_cao(bao_cao_id);
CREATE INDEX idx_ls_ntd ON lich_su_duyet_ntd(ntd_id,thuc_hien_luc);
CREATE INDEX idx_ls_tin ON lich_su_duyet_tin(tin_id,thuc_hien_luc);
CREATE INDEX idx_ls_cc ON lich_su_duyet_cham_cong(cham_cong_id,thuc_hien_luc);
CREATE INDEX idx_ls_luong ON lich_su_luong(bang_luong_id,thuc_hien_luc);
CREATE INDEX idx_ls_bc ON lich_su_xu_ly_bao_cao(bao_cao_id,thuc_hien_luc);
COMMIT;
